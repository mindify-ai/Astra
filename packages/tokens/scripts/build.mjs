// Generates CSS variables, a Tailwind v4 theme and a TS module from tokens.json.
// Run: pnpm --filter @astra/tokens build
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const tokens = JSON.parse(readFileSync(join(root, 'tokens.json'), 'utf8'))
const out = join(root, 'src', 'generated')
mkdirSync(out, { recursive: true })

const colors = tokens.color.tokens
const resolve = (value, theme) => {
  if (typeof value === 'string') {
    const alias = value.match(/^\{(.+)\}$/)
    if (alias) return resolve(colors.find((t) => t.name === alias[1]).value, theme)
    return value
  }
  return value[theme]
}
const shadows = tokens.shadow.tokens
const themeVars = (theme) =>
  [
    ...colors.map((t) => `  --${t.name}: ${resolve(t.value, theme)};`),
    // shadow-lg is exposed as --elevation-lg so it doesn't collide with Tailwind's --shadow-lg theme key
    ...shadows.map(
      (t) => `  --${t.name === 'shadow-lg' ? 'elevation-lg' : t.name}: ${resolve(t.value, theme)};`,
    ),
  ].join('\n')

const families = tokens.type.families
const styles = tokens.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family })))
const textVars = styles
  .map((s) =>
    [
      `  --text-${s.name}: ${s.fontSize};`,
      `  --text-${s.name}--line-height: ${s.lineHeight};`,
      s.letterSpacing ? `  --text-${s.name}--letter-spacing: ${s.letterSpacing};` : null,
      `  --text-${s.name}--font-weight: ${s.fontWeight};`,
    ]
      .filter(Boolean)
      .join('\n'),
  )
  .join('\n')

const css = `/* Generated by packages/tokens/scripts/build.mjs from tokens.json. Do not edit. */
:root,
:root[data-theme='dark'] {
  color-scheme: dark;
${themeVars('dark')}
}

:root[data-theme='light'] {
  color-scheme: light;
${themeVars('light')}
}

@theme inline {
  --color-*: initial;
  --color-transparent: transparent;
  --color-current: currentColor;
${colors.map((t) => `  --color-${t.name}: var(--${t.name});`).join('\n')}
  --shadow-lg: var(--elevation-lg);
  --shadow-focus: var(--focus-ring);
}

@theme {
  --font-sans: ${families.sans};
  --font-mono: ${families.mono};
  --text-*: initial;
${textVars}
  --radius-*: initial;
${tokens.radius.tokens.map((t) => `  --radius-${t.name.replace('radius-', '')}: ${t.value};`).join('\n')}
}
`
writeFileSync(join(out, 'theme.css'), css)

const ts = `// Generated by packages/tokens/scripts/build.mjs from tokens.json. Do not edit.
export const colors = ${JSON.stringify(
  Object.fromEntries(
    colors.map((t) => [t.name, { dark: resolve(t.value, 'dark'), light: resolve(t.value, 'light') }]),
  ),
  null,
  2,
)} as const

export type ColorToken = keyof typeof colors

export const typeStyles = ${JSON.stringify(Object.fromEntries(styles.map((s) => [s.name, s])), null, 2)} as const

export const fontFamilies = ${JSON.stringify(families, null, 2)} as const

export const sizes = ${JSON.stringify(Object.fromEntries(tokens.size.tokens.map((t) => [t.name, t.value])), null, 2)} as const
`
writeFileSync(join(out, 'tokens.ts'), ts)
console.log(`tokens: ${colors.length} colors, ${styles.length} type styles → src/generated`)
